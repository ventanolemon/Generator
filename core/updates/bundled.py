"""
Зашитый в сборку набор ключей выпуска — корень доверия клиента.

Это ЕДИНСТВЕННОЕ место, где приложение узнаёт, кому верить. Всё остальное
(обновления, пакеты узлов, ротация ключей) опирается отсюда.

## Почему в коде, а не в файле рядом

Файл рядом с исполняемым лежит в месте, доступном на запись, и подменяется
без всякого взлома. Константа в модуле — часть того же кода, что и проверка
подписи: чтобы её подменить, надо уже иметь право переписывать приложение,
а тогда обсуждать подпись поздно. Ключ у сервера **не спрашивают**: клиент,
берущий ключ у того же сервера, что и обновление, не проверяет ничего.

## Почему пусто по умолчанию

В репозитории настоящего ключа нет и быть не должно — приватная часть живёт
у выпускающего, публичная попадает сюда при сборке релиза. Пустой набор
означает «доверять некому», и клиент отвергает всё: и обновления, и пакеты.
Это правильное поведение по умолчанию. Обратное — «ключа нет, значит
проверять нечем, значит примем как есть» — ровно та дыра, ради закрытия
которой писался весь механизм.

## Как заполняется при выпуске

Сборочный скрипт подставляет сюда действующий набор с сервера
(`GET /updates/keys`) — ЦЕЛИКОМ, теми же байтами:

    BUNDLED_KEYSET = {
        "payload": '{"keys":[{"id":"…","public_key":"…","status":"active"}],'
                   '"sequence":1}',
        "signature": "",     # первый набор не подписан: подписывать нечем
    }

`payload` пересобирать нельзя ни при каких обстоятельствах: подпись
покрывает текст, а не смысл, и любое расхождение в сериализации сломает
проверку сразу у всех. Копируется ровно то, что отдал сервер.

Подставлять набор `sequence > 1` не только можно, но и нужно, если ротация
уже была: новая сборка тем самым получает актуальный корень, а не догоняет
цепочку с самого начала.
"""

from __future__ import annotations

BUNDLED_KEYSET: dict = {
    "payload": "",
    "signature": "",
}
