"""
Порождение ПАЧКИ вариантов: с показом хода и возможностью прервать.

Почему это отдельный модуль, а не три цикла `for` по представлениям
--------------------------------------------------------------------
Замер, из-за которого модуль появился. Время одной генерации по 89
статическим генераторам поставки: медиана порядка сотых долей секунды,
но у «Первого замечательного предела» — **от 3,7 до 13,1 секунды**
(медиана 9,0). Там символьное упрощение, и предела сверху у него нет.

Тридцать вариантов такого раздела — это около четырёх с половиной минут.
Простой цикл в обработчике кнопки означает четыре с половиной минуты
замершего окна: без единого признака жизни, без возможности отменить и
без понимания, сколько ещё ждать. Пользователь в такой ситуации
закрывает приложение, и правильно делает.

Поэтому пачка порождается ЗДЕСЬ, и здесь же живут три обязательных
свойства: видно ход, можно прервать, прерванное не теряется.

Почему не поток
---------------
`ui/qt_worker.py` заведён для СЕТЕВЫХ вызовов, где поток действительно
ждёт. Здесь работа вычислительная и упирается в интерпретатор: поток
освободил бы окно для перерисовки, но саму работу не ускорил, зато
потребовал бы таскать генератор между потоками. Генератор — общий объект
реестра, у него есть настраиваемое состояние (`configure`), и разделять
его между потоками ради перерисовки не стоит.

Взамен — стандартный для Qt приём: модальное окно хода и `processEvents`
между вариантами. Модальность здесь не украшение: она не пускает
пользователя нажимать кнопки того же окна, пока цикл не кончился, и тем
снимает повторный вход, которым `processEvents` опасен.

Почему окно хода не мигает на быстрых разделах
-----------------------------------------------
`setMinimumDuration` — окно показывается, только если работа затянулась
дольше порога. Пять вариантов линала (сотые доли секунды) проходят
незаметно, тридцать вариантов предела — с полосой и кнопкой «Прервать».
Условие «показывать ли» решается временем, а не числом вариантов: одно и
то же N на разных разделах стоит по-разному.
"""

from __future__ import annotations

from typing import List, Optional

from PyQt6.QtCore import Qt
from PyQt6.QtWidgets import QApplication, QProgressDialog, QWidget

from core import StaticTask, TaskGenerator

#: Насколько работа должна затянуться, чтобы показать окно хода, мс.
SHOW_AFTER_MS = 400


def generate_variants(parent: QWidget, generator: TaskGenerator, count: int,
                      *, label: str = "Готовим варианты") -> List[StaticTask]:
    """
    Породить `count` вариантов, показывая ход и позволяя прервать.

    Возвращается то, что УСПЕЛИ породить. Прерывание на середине — не
    ошибка и не повод выбросить сделанное: преподаватель, нажавший
    «Прервать» на двадцатом варианте из пятидесяти, хотел двадцать, а не
    ноль. Пустой список означает, что не успели ни одного.

    Не-`StaticTask` пропускается молча: генератор группы может вернуть
    что-то иное, и ронять из-за этого всю пачку незачем.
    """
    count = max(0, int(count))
    if count <= 0:
        return []

    progress = QProgressDialog(f"{label}…", "Прервать", 0, count, parent)
    progress.setWindowTitle("Генерация")
    progress.setWindowModality(Qt.WindowModality.WindowModal)
    progress.setMinimumDuration(SHOW_AFTER_MS)
    progress.setAutoClose(True)
    progress.setAutoReset(True)

    out: List[StaticTask] = []
    try:
        for index in range(count):
            if progress.wasCanceled():
                break
            progress.setLabelText(f"{label}: {index + 1} из {count}")
            # ДО генерации, а не после: иначе окно хода не появится, пока
            # не закончится первый вариант, — а он и есть самый долгий на
            # медленных разделах.
            progress.setValue(index)
            QApplication.processEvents()
            if progress.wasCanceled():
                break
            task = generator.generate()
            if isinstance(task, StaticTask):
                out.append(task)
        progress.setValue(count)
    finally:
        # `close`, а не надежда на автозакрытие: при исключении внутри
        # генерации модальное окно осталось бы висеть поверх приложения.
        progress.close()
    return out


def was_interrupted(asked: int, got: int) -> Optional[str]:
    """
    Сообщение о том, что пачка вышла короче запрошенной, или None.

    Отдельной функцией, потому что говорить об этом обязаны все
    вызывающие, а формулировка должна быть одна. Молчаливое «выгрузили 12
    вместо 30» — это лист, который преподаватель раздаст, не пересчитав.
    """
    if got >= asked:
        return None
    if got == 0:
        return "Генерация прервана, ни одного варианта не готово."
    return (f"Генерация прервана: готово {got} из {asked}. "
            f"Дальше идёт то, что успели.")
